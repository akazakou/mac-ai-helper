// ShortcutDefinition.swift
// Defines a keyboard shortcut configuration for global hotkey detection.

import Carbon.HIToolbox
import CoreGraphics
import Foundation

struct ShortcutDefinition: Codable, Hashable, Sendable {
    /// CGKeyCode value for the target key
    var keyCode: UInt16
    /// CGEventFlags raw value representing modifier keys (CMD, Shift, etc.)
    var modifierFlags: UInt64
    /// Whether the shortcut requires a double-press of the key
    var doubleTap: Bool
    /// Human-readable description, e.g. "⌘C+C"
    var displayName: String

    // MARK: - Display Name Generation

    /// Generates a human-readable display name from keyCode and modifierFlags.
    static func buildDisplayName(
        keyCode: UInt16, modifierFlags: UInt64, doubleTap: Bool
    ) -> String {
        let flags = CGEventFlags(rawValue: modifierFlags)
        var parts: [String] = []

        if flags.contains(.maskControl) { parts.append("⌃") }
        if flags.contains(.maskAlternate) { parts.append("⌥") }
        if flags.contains(.maskShift) { parts.append("⇧") }
        if flags.contains(.maskCommand) { parts.append("⌘") }

        let keyName = Self.keyName(for: keyCode)
        parts.append(keyName)

        let base = parts.joined()
        return doubleTap ? "\(base) + \(keyName)" : base
    }

    /// Returns a human-readable name for a given CGKeyCode.
    static func keyName(for keyCode: UInt16) -> String {
        // Common key mappings using Carbon virtual key codes
        switch Int(keyCode) {
        case kVK_ANSI_A: return "A"
        case kVK_ANSI_B: return "B"
        case kVK_ANSI_C: return "C"
        case kVK_ANSI_D: return "D"
        case kVK_ANSI_E: return "E"
        case kVK_ANSI_F: return "F"
        case kVK_ANSI_G: return "G"
        case kVK_ANSI_H: return "H"
        case kVK_ANSI_I: return "I"
        case kVK_ANSI_J: return "J"
        case kVK_ANSI_K: return "K"
        case kVK_ANSI_L: return "L"
        case kVK_ANSI_M: return "M"
        case kVK_ANSI_N: return "N"
        case kVK_ANSI_O: return "O"
        case kVK_ANSI_P: return "P"
        case kVK_ANSI_Q: return "Q"
        case kVK_ANSI_R: return "R"
        case kVK_ANSI_S: return "S"
        case kVK_ANSI_T: return "T"
        case kVK_ANSI_U: return "U"
        case kVK_ANSI_V: return "V"
        case kVK_ANSI_W: return "W"
        case kVK_ANSI_X: return "X"
        case kVK_ANSI_Y: return "Y"
        case kVK_ANSI_Z: return "Z"
        case kVK_ANSI_0: return "0"
        case kVK_ANSI_1: return "1"
        case kVK_ANSI_2: return "2"
        case kVK_ANSI_3: return "3"
        case kVK_ANSI_4: return "4"
        case kVK_ANSI_5: return "5"
        case kVK_ANSI_6: return "6"
        case kVK_ANSI_7: return "7"
        case kVK_ANSI_8: return "8"
        case kVK_ANSI_9: return "9"
        case kVK_ANSI_Minus: return "-"
        case kVK_ANSI_Equal: return "="
        case kVK_ANSI_LeftBracket: return "["
        case kVK_ANSI_RightBracket: return "]"
        case kVK_ANSI_Backslash: return "\\"
        case kVK_ANSI_Semicolon: return ";"
        case kVK_ANSI_Quote: return "'"
        case kVK_ANSI_Comma: return ","
        case kVK_ANSI_Period: return "."
        case kVK_ANSI_Slash: return "/"
        case kVK_ANSI_Grave: return "`"
        case kVK_Return: return "↩"
        case kVK_Tab: return "⇥"
        case kVK_Space: return "Space"
        case kVK_Delete: return "⌫"
        case kVK_ForwardDelete: return "⌦"
        case kVK_Escape: return "⎋"
        case kVK_LeftArrow: return "←"
        case kVK_RightArrow: return "→"
        case kVK_UpArrow: return "↑"
        case kVK_DownArrow: return "↓"
        case kVK_Home: return "↖"
        case kVK_End: return "↘"
        case kVK_PageUp: return "⇞"
        case kVK_PageDown: return "⇟"
        case kVK_F1: return "F1"
        case kVK_F2: return "F2"
        case kVK_F3: return "F3"
        case kVK_F4: return "F4"
        case kVK_F5: return "F5"
        case kVK_F6: return "F6"
        case kVK_F7: return "F7"
        case kVK_F8: return "F8"
        case kVK_F9: return "F9"
        case kVK_F10: return "F10"
        case kVK_F11: return "F11"
        case kVK_F12: return "F12"
        default: return "Key\(keyCode)"
        }
    }

    /// Extracts modifier flags from CGEventFlags, keeping only ⌘⇧⌥⌃ bits.
    static func sanitizedModifierFlags(_ flags: CGEventFlags) -> UInt64 {
        var result: UInt64 = 0
        if flags.contains(.maskCommand) { result |= CGEventFlags.maskCommand.rawValue }
        if flags.contains(.maskShift) { result |= CGEventFlags.maskShift.rawValue }
        if flags.contains(.maskAlternate) { result |= CGEventFlags.maskAlternate.rawValue }
        if flags.contains(.maskControl) { result |= CGEventFlags.maskControl.rawValue }
        return result
    }
}
