// AboutSettingsView.swift
// Settings tab showing app version, legal links, and AI content disclaimer.

import SwiftUI

struct AboutSettingsView: View {
    /// App version from the main bundle (e.g. "1.0.0")
    private var appVersion: String {
        Bundle.main.object(forInfoDictionaryKey: "CFBundleShortVersionString") as? String ?? "–"
    }

    /// Build number from the main bundle (e.g. "1")
    private var buildNumber: String {
        Bundle.main.object(forInfoDictionaryKey: "CFBundleVersion") as? String ?? "–"
    }

    var body: some View {
        VStack(spacing: 0) {
            ScrollView {
                VStack(alignment: .leading, spacing: 20) {
                    // App identity header
                    appHeader

                    Divider()

                    // AI-generated content disclaimer
                    aiDisclaimerSection

                    Divider()

                    // Third-party API notice
                    apiChargesSection

                    Divider()

                    // Legal links
                    legalLinksSection

                    Divider()

                    // Copyright
                    Text("© 2026 Castloud. Licensed under GPL-3.0.")
                        .font(.caption)
                        .foregroundStyle(.tertiary)
                        .frame(maxWidth: .infinity, alignment: .center)
                }
                .padding()
            }
        }
    }

    // MARK: - App Header

    private var appHeader: some View {
        HStack(spacing: 16) {
            Image(systemName: "brain.head.profile")
                .font(.system(size: 48))
                .foregroundStyle(.tint)

            VStack(alignment: .leading, spacing: 4) {
                Text("Mac AI Helper")
                    .font(.title2.bold())

                Text("Version \(appVersion) (\(buildNumber))")
                    .font(.caption)
                    .foregroundStyle(.secondary)

                Text("A native macOS menu bar utility for AI-powered text and screenshot analysis.")
                    .font(.callout)
                    .foregroundStyle(.secondary)
                    .fixedSize(horizontal: false, vertical: true)
            }
        }
    }

    // MARK: - AI Disclaimer

    private var aiDisclaimerSection: some View {
        VStack(alignment: .leading, spacing: 8) {
            Label("AI-Generated Content", systemImage: "exclamationmark.triangle")
                .font(.headline)

            Text("""
                Responses displayed in this app are generated by third-party AI \
                services (OpenAI, Anthropic, Google). AI-generated content may be \
                inaccurate, incomplete, or misleading. Always verify important \
                information independently. Do not rely on AI responses as a \
                substitute for professional advice.
                """)
                .font(.callout)
                .foregroundStyle(.secondary)
                .fixedSize(horizontal: false, vertical: true)
        }
    }

    // MARK: - API Charges

    private var apiChargesSection: some View {
        VStack(alignment: .leading, spacing: 8) {
            Label("Third-Party API Charges", systemImage: "creditcard")
                .font(.headline)

            Text("""
                This app connects to AI provider APIs using API keys that you \
                provide. You are solely responsible for all charges incurred \
                from your use of third-party APIs, including per-token and \
                per-request fees. Castloud has no control over third-party \
                pricing and is not responsible for any charges you incur.
                """)
                .font(.callout)
                .foregroundStyle(.secondary)
                .fixedSize(horizontal: false, vertical: true)
        }
    }

    // MARK: - Legal Links

    private var legalLinksSection: some View {
        VStack(alignment: .leading, spacing: 12) {
            Text("Legal")
                .font(.headline)

            HStack(spacing: 24) {
                Link(destination: AppConstants.privacyPolicyURL) {
                    Label("Privacy Policy", systemImage: "hand.raised")
                }

                Link(destination: AppConstants.licenseURL) {
                    Label("License (GPL-3.0)", systemImage: "doc.text")
                }

                Link(destination: AppConstants.sourceCodeURL) {
                    Label("Source Code", systemImage: "chevron.left.forwardslash.chevron.right")
                }
            }
            .font(.callout)
        }
    }
}
